"""README front matter of qualitative deliveries, and the INDEX.md built from it.

Each delivery is a folder `<results_dir>/qualitative/<topic>-<MM-DD>/` whose README.md starts with

    ---
    title: Ear heatmaps on IBL
    date: 2026-09-18
    data_version: head-fixed-v2
    question: Why do the ear channels fire on paws?
    models: trunks/face+...; dedicated/hantman-mv
    outputs: ear_heatmaps_ibl.mp4, stats.csv
    finding: one sentence
    ---

The block is plain `key: value` lines (not general YAML): a value is one line and may contain
colons. The writers and the parser live here so the keys cannot drift apart.
"""

from pathlib import Path

KEYS = ("title", "date", "data_version", "question", "models", "outputs", "finding")


def front_matter_lines(
    title: str, date: str, data_version: str, question: str, models: str, outputs: str,
    finding: str,
) -> list[str]:
    """The front matter block as lines, `---` fences included.

    Raises:
        ValueError: if a value spans several lines
    """
    values = dict(title=title, date=date, data_version=data_version, question=question,
                  models=models, outputs=outputs, finding=finding)
    for key, value in values.items():
        if "\n" in str(value):
            raise ValueError(f"front matter value of '{key}' must be one line")
    return ["---", *(f"{key}: {values[key]}" for key in KEYS), "---"]


def front_matter(**fields: str) -> str:
    """The front matter block as text ending in a newline (fields as `front_matter_lines`)."""
    return "\n".join(front_matter_lines(**fields)) + "\n"


def parse_front_matter(text: str) -> dict[str, str] | None:
    """Front matter of README text, or None if it has none (or an unterminated one)."""
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end < 0:
        return None
    fm = {}
    for line in text[3:end].strip().splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            fm[key.strip()] = value.strip()
    return fm or None


def collect_deliveries(qualitative_dir: Path) -> list[tuple[str, dict[str, str] | None]]:
    """(folder name, front matter or None) for every delivery folder, sorted by name."""
    out = []
    for folder in sorted(Path(qualitative_dir).glob("*/")):
        readme = folder / "README.md"
        out.append((folder.name, parse_front_matter(readme.read_text()) if readme.exists()
                    else None))
    return out


def index_markdown(results_name: str, deliveries: list[tuple[str, dict[str, str] | None]]) -> str:
    """INDEX.md text: one table row per delivery with front matter, then the folders without."""
    rows = [(name, fm) for name, fm in deliveries if fm]
    missing = [name for name, fm in deliveries if not fm]
    lines = [f"# Qualitative evaluations — {results_name}", "",
             "Generated by `scripts/evaluation/qualitative/qualitative_index.py` from each "
             "folder's README front matter; edit the",
             "READMEs, not this file.", "",
             "| folder | date | question | models | finding | outputs |",
             "|---|---|---|---|---|---|"]
    for name, fm in rows:
        def cell(key, fm=fm):
            return str(fm.get(key, "")).replace("|", "\\|").replace("\n", " ")
        lines.append(f"| [`{name}`]({name}/README.md) | {cell('date')} | {cell('question')} "
                     f"| {cell('models')} | {cell('finding')} | {cell('outputs')} |")
    if missing:
        lines += ["", "Folders without a README front matter (add one): "
                  + ", ".join(f"`{n}`" for n in missing)]
    return "\n".join(lines) + "\n"
